/**
 * Thai Polite Particle Gender Normalizer
 *
 * แก้ไขปัญหาคำลงท้ายไม่ตรงกับเพศของผู้พากย์เสียง (เช่น เสียงผู้หญิงพูด "ครับ" หรือเสียงผู้ชายพูด "ค่ะ/นะคะ")
 * ปรับปรุงทั้งบทพูด (Voiceover) ที่ส่งให้ AI สังเคราะห์เสียง และตัวหนังสือคำบรรยาย (Subtitles)
 */

export type VoiceGender = "female" | "male";

/**
 * ปรับคำลงท้ายสุภาพในข้อความภาษาไทยให้ตรงกับเพศของเสียงพากย์
 *
 * @param text ข้อความสคริปต์หรือบทพากย์ภาษาไทย
 * @param gender เพศของเสียงพากย์ ("female" หรือ "male")
 * @returns ข้อความที่ปรับคำลงท้ายถูกต้องตามเพศของผู้พากย์
 */
export function alignThaiPoliteParticles(text: string, gender?: VoiceGender): string {
  if (!text || typeof text !== "string") return "";
  if (!gender) return text;

  let result = text;

  if (gender === "female") {
    // ----------------------------------------------------
    // แปลงคำลงท้ายของผู้ชาย -> เป็นคำลงท้ายของผู้หญิง (Female Voice)
    // ----------------------------------------------------
    // 1. คำถาม/ความสงสัย: "ไหมครับ", "มั้ยครับ", "เหรอครับ", "หรือเปล่าครับ" -> ลงท้ายด้วย "คะ"
    result = result
      .replace(/(ใช่[ไห]ม|ไหม|มั้ย|เหรอ|หรือเปล่า|รึเปล่า|หรือยัง|รึยัง|ยังไง|บ้าง|หรือไม่|อะไร|ที่ไหน|เมื่อไหร่|อย่างไร)ครับ/g, "$1คะ")
      .replace(/(ใช่[ไห]ม|ไหม|มั้ย|เหรอ|หรือเปล่า|รึเปล่า|หรือยัง|รึยัง|ยังไง|บ้าง|หรือไม่|อะไร|ที่ไหน|เมื่อไหร่|อย่างไร)นะครับ/g, "$1นะคะ")
      .replace(/(ใช่[ไห]ม|ไหม|มั้ย|เหรอ|หรือเปล่า|รึเปล่า|หรือยัง|รึยัง|ยังไง|บ้าง|หรือไม่|อะไร|ที่ไหน|เมื่อไหร่|อย่างไร)คับ/g, "$1คะ");

    // 2. คำลงท้ายบอกเล่า/เชิญชวน: "นะครับ", "นะคับ" -> "นะคะ"
    result = result.replace(/นะครับ/g, "นะคะ").replace(/นะคับ/g, "นะคะ");

    // 3. วลียอดนิยมที่มักใช้ "ครับ": "เลยครับ", "ครับผม", "จริงครับ", "ด้วยครับ"
    result = result
      .replace(/ครับผม/g, "ค่ะ")
      .replace(/เลยครับ/g, "เลยค่ะ")
      .replace(/เลยคับ/g, "เลยค่ะ")
      .replace(/ดีครับ/g, "ดีค่ะ")
      .replace(/จริงครับ/g, "จริงค่ะ")
      .replace(/ด้วยครับ/g, "ด้วยค่ะ")
      .replace(/ต่อครับ/g, "ต่อค่ะ")
      .replace(/ก่อนครับ/g, "ก่อนค่ะ")
      .replace(/หมดครับ/g, "หมดค่ะ");

    // 4. คำว่า "ครับ", "คับ", "ค้าบ" ทั่วไปที่อยู่ท้ายประโยค หรือท้ายวรรค
    result = result.replace(/ครับ(?=[\s\.,!?:;\)\]\}\n]|$)/g, "ค่ะ");
    result = result.replace(/คับ(?=[\s\.,!?:;\)\]\}\n]|$)/g, "ค่ะ");
    result = result.replace(/ค้าบ(?=[\s\.,!?:;\)\]\}\n]|$)/g, "ค่า");

  } else {
    // ----------------------------------------------------
    // แปลงคำลงท้ายของผู้หญิง -> เป็นคำลงท้ายของผู้ชาย (Male Voice)
    // ----------------------------------------------------
    // 1. คำลงท้าย "นะคะ", "นะค่ะ", "นะค้า" -> "นะครับ"
    result = result.replace(/นะ(คะ|ค่ะ|ค้า)/g, "นะครับ");

    // 2. คำลงท้ายคำถาม "ไหมคะ", "มั้ยคะ", "เหรอคะ" -> "...ครับ"
    result = result
      .replace(/(ใช่[ไห]ม|ไหม|มั้ย|เหรอ|หรือเปล่า|รึเปล่า|หรือยัง|รึยัง|ยังไง|บ้าง)(คะ|ค่ะ)/g, "$1ครับ");

    // 3. วลียอดนิยมที่มักใช้ "ค่ะ": "เลยค่ะ", "จริงค่ะ", "ด้วยค่ะ"
    result = result
      .replace(/เลย(ค่ะ|คะ|ค่า)/g, "เลยครับ")
      .replace(/ดี(ค่ะ|คะ)/g, "ดีครับ")
      .replace(/จริง(ค่ะ|คะ)/g, "จริงครับ")
      .replace(/ด้วย(ค่ะ|คะ)/g, "ด้วยครับ")
      .replace(/หมด(ค่ะ|คะ)/g, "หมดครับ");

    // 4. คำว่า "ค่ะ", "คะ", "ค่า" ทั่วไปที่อยู่ท้ายประโยค หรือท้ายวรรค
    result = result.replace(/(ค่ะ|คะ)(?=[\s\.,!?:;\)\]\}\n]|$)/g, "ครับ");
    result = result.replace(/ค่า(?=[\s\.,!?:;\)\]\}\n]|$)/g, "ครับ");
  }

  return result;
}
